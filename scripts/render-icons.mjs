// Renders the extension icons from the shared mark, src/assets/brand/frunchy-mark.svg.
// The mark's shapes are copied into each icon SVG rather than linked with <image>:
// rsvg-convert rasterizes a linked SVG at its own size and then scales the bitmap,
// which made the 128 px store icon blurry. Needs rsvg-convert (librsvg).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const brand = "src/assets/brand";
const icons = "src/assets/icons";
const surface = "#13111a";

const mark = readFileSync(join(brand, "frunchy-mark.svg"), "utf8");
// The root's fill (fill="none") applies to the shapes too; without it the open frame path is filled black.
const fill = mark.match(/<svg[^>]*\sfill="([^"]*)"/)?.[1];
const shapes = mark
  .replace(/^[\s\S]*?<svg[^>]*>/, "")
  .replace(/<\/svg>\s*$/, "")
  .replace(/<!--[\s\S]*?-->/g, "")
  .split("\n")
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line) => `    ${line}`)
  .join("\n");

// The 48-unit tile: the mark (48 units) drawn 40 units wide, 4 units in from each edge.
const tile = `  <rect width="48" height="48" rx="10" fill="${surface}"/>
  <g transform="translate(4 4) scale(${40 / 48})"${fill ? ` fill="${fill}"` : ""}>
${shapes}
  </g>`;

const icon = (size, comment, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}">
  <!-- ${comment}
       Generated by scripts/render-icons.mjs from frunchy-mark.svg; edit the mark, not this file. -->
${body}
</svg>
`;

const toolbar = icon(
  48,
  `Extension icon: the mark on a surface (${surface}) tile, so it reads on light and dark toolbars.`,
  tile,
);
// The store asks for a 96 px artwork with 16 px of transparent padding in a 128 px icon.
const store = icon(
  128,
  "Store icon: the toolbar tile at 96 px with 16 px of transparent padding.",
  `<g transform="translate(16 16) scale(2)">
${tile.replace(/^/gm, "  ")}
</g>`,
);

writeFileSync(join(brand, "frunchy-icon.svg"), toolbar);
writeFileSync(join(brand, "frunchy-icon-128.svg"), store);

const render = (svg, size) =>
  execFileSync("rsvg-convert", ["-w", String(size), "-h", String(size), "-o", join(icons, `frunchy${size}.png`), join(brand, svg)]);
for (const size of [16, 32, 48]) render("frunchy-icon.svg", size);
render("frunchy-icon-128.svg", 128);
console.log(`${icons}/frunchy{16,32,48,128}.png`);
